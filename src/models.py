from dataclasses import dataclass, field
from typing import List, Dict, Optional, Tuple, Any


@dataclass
class Parcel:
    """
    Represents a parcel to be delivered.
    
    Attributes:
        id (str): Unique parcel identifier (e.g., 'P01').
        customer_name (str): Name of recipient.
        destination (str): Delivery point node ID (e.g., 'Sector_14').
        weight (int): Weight in kilograms (integer for discrete 0/1 Knapsack).
        priority (int): Priority level from 1 (lowest) to 10 (highest/critical).
        deadline_hours (float): Delivery deadline from dispatch (in hours).
        value (int): Computed priority/utility score for Knapsack DP.
    """
    id: str
    customer_name: str
    destination: str
    weight: int
    priority: int
    deadline_hours: float
    value: int = 0

    def __post_init__(self):
        # Calculate utility/value if not explicitly provided:
        # High priority + tighter deadline = higher utility value
        if self.value <= 0:
            urgency_score = max(1, int(24 - self.deadline_hours))
            self.value = (self.priority * 10) + urgency_score

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "customer_name": self.customer_name,
            "destination": self.destination,
            "weight": self.weight,
            "priority": self.priority,
            "deadline_hours": self.deadline_hours,
            "value": self.value
        }

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "Parcel":
        return cls(
            id=d["id"],
            customer_name=d.get("customer_name", "Customer"),
            destination=d["destination"],
            weight=int(d["weight"]),
            priority=int(d.get("priority", 5)),
            deadline_hours=float(d.get("deadline_hours", 12.0)),
            value=int(d.get("value", 0))
        )


@dataclass
class DeliveryPoint:
    """Represents a physical delivery node in the road network."""
    id: str
    name: str
    description: str = ""


@dataclass
class DeliveryPlan:
    """Summary of the complete planned trip generated by the courier system."""
    vehicle_capacity: int
    all_parcels: List[Parcel]
    sorted_parcels: List[Parcel]
    selected_parcels: List[Parcel]
    deferred_parcels: List[Parcel]
    total_weight: int
    total_value: int
    capacity_utilization_pct: float
    dp_table: List[List[int]]
    delivery_route: List[str]               # Ordered stops (e.g. Hub -> D1 -> D3 -> Hub)
    turn_by_turn_path: List[str]           # Detailed road segments traversed
    total_route_distance_km: float
    stage_runtimes_ms: Dict[str, float] = field(default_factory=dict)
